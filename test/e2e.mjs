// End-to-end walk of the core loop on the live site, two people (owner + invited partner), phone viewport.
// Run: /usr/bin/node test/e2e.mjs  (uses Tab's Browserbase door; screenshots go to SHOTS)
import fs from 'node:fs';
import Browserbase from '@browserbasehq/sdk';
import { chromium } from 'playwright-core';
const URL_ = process.env.APP_URL || 'https://accountability-ng.vercel.app';
const SHOTS = process.env.SHOTS || '/home/user/tab/files/accountability/screenshots';
const cap = JSON.parse(fs.readFileSync('/home/user/tab/.vendor-capability.json', 'utf8'));
const bb = new Browserbase({ apiKey: cap.token, baseURL: cap.base_url + '/browserbase' });
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);
const results = [];
const check = (name, ok, extra = '') => { results.push({ name, ok: !!ok, extra }); log(ok ? 'PASS' : 'FAIL', name, extra); };
const session = await bb.sessions.create({ projectId: 'f2ae15a0-a894-4419-977f-d52f52483f0c', userMetadata: { task: process.env.TAB_TASK_ID || 'accountability-e2e' }, timeout: 900 });
log('session', session.id);
const browser = await chromium.connectOverCDP(session.connectUrl);
const UA = 'Mozilla/5.0 (Linux; Android 14; Redmi A5) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Mobile Safari/537.36';
const mk = async () => { const c = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, userAgent: UA }); const p = await c.newPage(); PAGES.push(p); p.on('dialog', d => d.accept(d.type() === 'prompt' ? (d.defaultValue() || 'other') : undefined)); p.on('pageerror', e => log('PAGEERROR', e.message)); return p; };
const PAGES = [];
const shot = async (p, name) => { await p.waitForTimeout(500); await p.screenshot({ path: `${SHOTS}/${name}.png` }); log('shot', name); };
const btn = (p, name) => p.getByRole('button', { name, exact: false }).first();
try {
  const A = await mk();
  await A.goto(URL_, { waitUntil: 'networkidle' });
  await btn(A, 'Start privately').waitFor({ timeout: 20000 });
  await shot(A, '01-welcome');
  await btn(A, 'Start privately').click();
  await A.locator('#by').waitFor({ timeout: 20000 });
  await A.selectOption('#by', '1994'); await A.fill('#nm', 'Dami');
  await btn(A, 'Continue').click();
  await btn(A, 'Yes, include it').click();
  await btn(A, 'Start').click();
  await btn(A, 'Reading').click();
  await A.locator('#t').waitFor();
  await A.fill('#w', 'I want to finish 12 books this year and grow my mind.');
  await btn(A, 'An amount').click();
  await A.fill('#tv', '10'); await A.fill('#tu', 'pages');
  await shot(A, '02-create-commitment');
  await btn(A, 'I commit').click();
  await A.getByText('Did you do it today?').waitFor({ timeout: 20000 });
  check('owner created commitment and sees today check-in', true);
  await A.waitForTimeout(2600);
  await shot(A, '03-today');
  // invite
  await A.getByRole('link', { name: 'Partners' }).click();
  await btn(A, 'Invite a friend').click();
  await A.fill('#il', 'Tolu');
  await btn(A, 'Create invite link').click();
  await A.getByText('Your link is ready').waitFor({ timeout: 20000 });
  const link = (await A.locator('p.small.muted').first().innerText()).trim();
  check('invite link created', /\/#\/join\/[0-9a-f]{24}$/.test(link), link.replace(/[0-9a-f]{24}$/, '<token>'));
  await shot(A, '04-invite');
  // partner accepts
  const B = await mk();
  await B.goto(link, { waitUntil: 'networkidle' });
  await B.getByText('invited to be someone').waitFor({ timeout: 20000 });
  await btn(B, 'Start privately').click();
  await B.locator('#by').waitFor({ timeout: 20000 });
  await B.selectOption('#by', '1990'); await B.fill('#nm', 'Tolu');
  await btn(B, 'Continue').click();
  await B.getByText('invited you').waitFor({ timeout: 20000 });
  await shot(B, '05-partner-invite');
  await btn(B, 'Accept and support').click();
  await B.getByText('You\u2019re supporting').waitFor({ timeout: 20000 });
  check('partner accepted invite', await B.getByText('Read 10 pages every day').count() > 0);
  // owner struggles -> recovery
  await A.getByRole('link', { name: 'Today' }).click();
  await btn(A, 'Struggling').click();
  await A.getByText('Let\u2019s take a breath').waitFor({ timeout: 20000 });
  await btn(A, 'Change my plan').click();
  await btn(A, 'Tired').click(); await btn(A, 'Distracted').click();
  await btn(A, 'Next').click();
  await A.fill('#rn', 'Came home late, scrolled my phone in bed.');
  await btn(A, 'Next').click();
  await A.getByText('What should we change?').waitFor();
  const sugg = await A.locator('.toggle b').allInnerTexts();
  check('recovery suggests up to 3 rule-based changes', sugg.length >= 1 && sugg.length <= 3, sugg.join(' | '));
  await shot(A, '06-recovery-suggestions');
  await btn(A, 'Update my plan').click();
  await A.getByText('Start a Comeback Mission?').waitFor({ timeout: 20000 });
  await shot(A, '07-plan-updated');
  // partner sees status only and encourages
  await B.reload({ waitUntil: 'networkidle' });
  await B.getByText('Today: Struggling').waitFor({ timeout: 20000 });
  const bText = await B.locator('main').innerText();
  check('partner sees status (Struggling)', bText.includes('Today: Struggling'));
  check('partner does NOT see private note or why by default', !bText.includes('scrolled my phone') && !bText.includes('12 books'));
  await shot(B, '08-partner-sees-status');
  await btn(B, 'Encourage').click();
  await B.waitForTimeout(1200);
  await B.getByRole('button', { name: 'Message' }).first().click();
  await B.fill('#mt', 'You\u2019ve got this, Dami. Even 5 pages counts!');
  await btn(B, 'Send').click();
  await B.getByText('Even 5 pages counts').waitFor({ timeout: 20000 });
  check('partner sent encouragement + message', true);
  // owner turns the day around -> recovered setback
  await A.getByRole('link', { name: 'Today' }).click();
  await A.reload({ waitUntil: 'networkidle' });
  await A.getByText('New from your partner').waitFor({ timeout: 20000 });
  check('owner sees partner encouragement banner', true);
  await btn(A, 'Change').click();
  await btn(A, 'Done').click();
  await A.waitForTimeout(1500);
  await A.getByRole('link', { name: 'Journey' }).click();
  await A.getByText('Recovered setbacks').waitFor({ timeout: 20000 });
  await A.waitForTimeout(2500);
  const jt = await A.locator('main').innerText();
  check('journey shows 1 recovered setback', /\n1\nRecovered setbacks/.test(jt) || /1\s*Recovered setbacks/.test(jt), jt.replace(/\s+/g, ' ').slice(0, 220));
  await shot(A, '09-journey');
  await A.getByRole('link', { name: 'Partners' }).click();
  await btn(A, 'Messages').click();
  await A.getByText('Even 5 pages counts').waitFor({ timeout: 20000 });
  check('owner reads partner message', true);
  await shot(A, '10-owner-messages');
  await A.getByRole('link', { name: 'Partners' }).click();
  await btn(A, 'What they see').click();
  await A.getByText('Commitment title').waitFor();
  await shot(A, '11-sharing-controls');
  // SOS
  await btn(A, 'I need support').click();
  await btn(A, 'calmer').click();
  await A.getByText('Free help, any time').waitFor();
  check('SOS shows crisis lines', (await A.locator('.full').innerText()).includes('0809 111 6264'));
  await shot(A, '12-sos');
  await btn(A, 'Let my partner know').click();
  await A.waitForTimeout(1500);
  await B.getByRole('link', { name: 'Partners' }).click();
  await B.reload({ waitUntil: 'networkidle' });
  await B.getByRole('button', { name: 'Message' }).first().click();
  await B.getByText('Support request').waitFor({ timeout: 20000 });
  check('partner receives SOS notification', true);
  await shot(B, '13-partner-sos');
} catch (e) {
  check('script completed', false, e.message.split('\n').slice(0,3).join(' / '));
  for (let i = 0; i < PAGES.length; i++) await PAGES[i].screenshot({ path: `/tmp/ap-fail-${i}.png` }).catch(() => {});
} finally {
  fs.writeFileSync(`${SHOTS}/../e2e-results.json`, JSON.stringify({ at: new Date().toISOString(), url: URL_, results }, null, 1));
  await browser.close().catch(() => {});
  await bb.sessions.update(session.id, { projectId: 'f2ae15a0-a894-4419-977f-d52f52483f0c', status: 'REQUEST_RELEASE' }).catch(() => {});
  log('done', results.filter(r => r.ok).length + '/' + results.length);
}
